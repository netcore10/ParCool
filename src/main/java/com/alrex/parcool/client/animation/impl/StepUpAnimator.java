	private final Clip clip;

	public StepUpAnimator(boolean rightLeads) {
		this.clip = rightLeads ? RIGHT : LEFT;
	}

	@Override
	public boolean shouldRemoved(Player player, Parkourability parkourability) {
		return getTick() >= clip.length * 20;
	}

	@Override
	public void animatePost(Player player, Parkourability parkourability, PlayerModelTransformer transformer) {
		float ticks = getTick() + transformer.getPartialTick();
		float time = ticks / 20f;
		float fade = Math.min(1f, ticks / FADE_IN_TICKS);

		float[] r;
		float[] p;
		if ((r = sample(clip.rightArmRot, time)) != null) transformer.rotateRightArm(rad(r[0]), rad(r[1]), rad(r[2]), fade);
		if ((p = sample(clip.rightArmPos, time)) != null) transformer.translateRightArm(p[0] * fade, -p[1] * fade, p[2] * fade);
		if ((r = sample(clip.leftArmRot, time)) != null) transformer.rotateLeftArm(rad(r[0]), rad(r[1]), rad(r[2]), fade);
		if ((p = sample(clip.leftArmPos, time)) != null) transformer.translateLeftArm(p[0] * fade, -p[1] * fade, p[2] * fade);
		if ((r = sample(clip.rightLegRot, time)) != null) transformer.rotateRightLeg(rad(r[0]), rad(r[1]), rad(r[2]), fade);
		if ((p = sample(clip.rightLegPos, time)) != null) transformer.translateRightLeg(p[0] * fade, -p[1] * fade, p[2] * fade);
		if ((r = sample(clip.leftLegRot, time)) != null) transformer.rotateLeftLeg(rad(r[0]), rad(r[1]), rad(r[2]), fade);
		if ((p = sample(clip.leftLegPos, time)) != null) transformer.translateLeftLeg(p[0] * fade, -p[1] * fade, p[2] * fade);
		// Head keeps following the camera; the keyframes add on top (PAL replaced the look direction)
		if ((r = sample(clip.headRot, time)) != null) transformer.rotateAdditionallyHeadPitch(r[0] * fade);
		if ((p = sample(clip.headPos, time)) != null) transformer.translateHead(p[0] * fade, -p[1] * fade, p[2] * fade);
		ModelPart body = transformer.getRawModel().body;
		if ((r = sample(clip.torsoRot, time)) != null) {
			body.xRot = Mth.lerp(fade, body.xRot, rad(r[0]));
			body.yRot = Mth.lerp(fade, body.yRot, rad(r[1]));
			body.zRot = Mth.lerp(fade, body.zRot, rad(r[2]));
		}
		if ((p = sample(clip.torsoPos, time)) != null) {
			body.x += p[0] * fade;
			body.y -= p[1] * fade;
			body.z += p[2] * fade;
		}
		transformer.end();
	}

	/** Channels the export didn't key are left alone. */
	private static float[] sample(Track track, float time) {
		return track == null ? null : track.sample(time);
	}

	private static float rad(float degrees) {
		return degrees * Mth.DEG_TO_RAD;
	}

	private record Clip(float length, Track torsoRot, Track torsoPos, Track headRot, Track headPos,
						Track rightArmRot, Track rightArmPos, Track leftArmRot, Track leftArmPos,
						Track rightLegRot, Track rightLegPos, Track leftLegRot, Track leftLegPos) {
	}

	/** Keyframes of one channel (x, y, z), linearly interpolated, held before the first and after the last. */
	private record Track(float[] times, float[][] values) {
		float[] sample(float time) {
			if (time <= times[0]) return values[0];
			for (int i = 1; i < times.length; i++) {
				if (time <= times[i]) {
					float t = (time - times[i - 1]) / (times[i] - times[i - 1]);
					float[] a = values[i - 1], b = values[i];
					return new float[]{Mth.lerp(t, a[0], b[0]), Mth.lerp(t, a[1], b[1]), Mth.lerp(t, a[2], b[2])};
				}
			}
			return values[values.length - 1];
		}
	}
